// Проверка разделителя «число / единица»: npx tsx src/ui/num.check.ts
import { splitValue } from './num';

const cases: [string, [string, string, string]][] = [
  ['$32.38 трлн ВВП', ['', '$32.38', 'трлн ВВП']],
  ['~$19 трлн ВВП', ['', '~$19', 'трлн ВВП']],
  ['2 300 – 2 700 школ', ['', '2 300 – 2 700', 'школ']],
  ['~60-65% мирового ВВП', ['', '~60-65%', 'мирового ВВП']],
  ['рост ~6.5%/год', ['рост', '~6.5%', '/год']],
  ['382 800 – 501 600 ₽', ['', '382 800 – 501 600', '₽']],
  ['442', ['', '442', '']],
  ['+12,2%', ['', '+12,2%', '']],
  ['< 1 мес на LTV', ['', '< 1', 'мес на LTV']],
  ['> 500 млн ₽', ['', '> 500', 'млн ₽']]
];

for (const [input, want] of cases) {
  const got = splitValue(input);
  if (got.join('|') !== want.join('|')) {
    throw new Error(`${input}: получено ${got.join('|')}, ожидалось ${want.join('|')}`);
  }
}
console.log(`ok: ${cases.length} значений разобраны верно`);
